import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { acaoSchema, atrasoDaAcao, revisaoSchema, tarefaDaAcao } from "../src/lib/acompanhamento.js";
const cid = "11111111-1111-4111-8111-111111111111";
const rid = "22222222-2222-4222-8222-222222222222";
const acao = acaoSchema.parse({ id: "33333333-3333-4333-8333-333333333333", titulo: "Revisar conversas", descricao: "Conferir os motivos de perda", responsavel: "Equipe", prazo: "2026-11-30", estado: "Planejado", criterio: "Registrar o diagnóstico", resultado: "" });
const ficha = { objetivo: "Melhorar agendamentos", instagram: "Sem dado", conteudo: "Conferir peças", leads: "Leitura existente", hipotese: "A validar", periodo_de: "2026-11-13", periodo_ate: "2026-11-26", notas: "", transcricao: "", fontes: ["https://example.test/fonte"], acoes: [acao], conversas: [] };
const r = revisaoSchema.parse({ id: rid, client_id: cid, data: "2026-11-27", titulo: "Revisão", prioridade: "Alta", proxima_checagem: "2026-12-04", versao: 0, dados: ficha });
assert.ok(tarefaDaAcao(r, acao, "Cliente de teste").description.includes(acao.id));
assert.equal(atrasoDaAcao(acao, "2026-12-01"), true);
assert.equal(atrasoDaAcao({ ...acao, estado: "Concluído" }, "2026-12-01"), false);
assert.equal(revisaoSchema.safeParse({ ...r, data: "2026-02-30" }).success, false);
assert.equal(revisaoSchema.safeParse({ ...r, dados: { ...ficha, fontes: ["javascript:alert(1)"] } }).success, false);
assert.equal(revisaoSchema.safeParse({ ...r, dados: { ...ficha, periodo_de: "2026-12-01" } }).success, false);
const db = new PGlite();
try {
  await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
    create table public.clients(id uuid primary key);
    create function public.is_app_admin() returns boolean language sql stable as $$ select coalesce(current_setting('test.admin', true), 'false') = 'true' $$;
    grant execute on function public.is_app_admin() to authenticated;
    insert into clients values ('${cid}');`);
  await db.exec(await readFile(new URL("../supabase/migrations/20261127183304_acompanhamento_revisoes.sql", import.meta.url), "utf8"));
  await db.query("insert into acompanhamento_revisoes(id,client_id,data,titulo,prioridade,dados) values($1,$2,'2026-11-27','Revisão','Alta',$3)", [rid, cid, ficha]);
  await db.exec("set role authenticated; set test.admin = 'false'");
  assert.equal((await db.query("select * from acompanhamento_revisoes")).rows.length, 0);
  await assert.rejects(db.query("update acompanhamento_revisoes set titulo='Invasão'"));
  await db.exec("set test.admin = 'true'");
  assert.equal((await db.query("select * from acompanhamento_revisoes")).rows.length, 1);
  await db.exec("reset role");
  const first = await db.query("update acompanhamento_revisoes set versao=1 where id=$1 and versao=0 returning id", [rid]);
  const stale = await db.query("update acompanhamento_revisoes set versao=1 where id=$1 and versao=0 returning id", [rid]);
  assert.equal(first.rows.length, 1); assert.equal(stale.rows.length, 0);
  await db.query("insert into acompanhamento_envios(revisao_id,acao_id,lista_id,estado) values($1,$2,'123','enviando')", [rid, acao.id]);
  await assert.rejects(db.query("insert into acompanhamento_envios(revisao_id,acao_id,lista_id,estado) values($1,$2,'123','enviando')", [rid, acao.id]));
  await db.exec("set role authenticated; set test.admin = 'false'");
  assert.equal((await db.query("select * from acompanhamento_envios")).rows.length, 0);
  await db.exec("reset role; set role anon");
  await assert.rejects(db.query("select * from acompanhamento_revisoes"));
} finally { await db.close(); }
console.log("Acompanhamento validado: datas, fontes, papéis, edição concorrente e intenção única de envio.");
