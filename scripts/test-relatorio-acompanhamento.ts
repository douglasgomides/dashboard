import assert from 'node:assert/strict';
import { montarRelatorioSemanal, secoesDoCliente } from '../src/lib/relatorio-acompanhamento.js';
import { fichaVazia, type Revisao } from '../src/lib/acompanhamento.js';
const clientes = [{ id: 'a', name: 'Cliente A', active: true }, { id: 'b', name: 'Cliente B', active: true }, { id: 'c', name: 'Cliente C', active: false }];
const ficha = fichaVazia();
const base: Revisao = { id: 'r', client_id: 'a', data: '2026-11-27', titulo: 'Revisão', prioridade: 'Alta', proxima_checagem: null, versao: 0, dados: { ...ficha, balanco: 'Melhorou', acertos: 'Mais agendamentos', decisao: 'Validar próximo teste' } };
const futuro = { ...base, id: 'futuro', data: '2026-12-02', dados: { ...base.dados, balanco: 'Piorou' as const } };
const antigo = { ...base, id: 'antigo', data: '2026-11-15' };
const r = montarRelatorioSemanal(clientes, [antigo, futuro, base], [], '2026-11-21', '2026-11-27', '2026-11-27');
assert.equal(r.itens.length, 2);
assert.equal(r.itens[0].revisao?.id, 'r', 'revisão futura não contamina o relatório');
assert.equal(r.itens[0].atualizada, true);
assert.equal(r.itens[1].revisao, null, 'cliente sem ficha continua no relatório');
assert.ok(r.itens[1].faltas.includes('Leads e agendamentos'));
assert.ok(secoesDoCliente(r.itens[0]).find(s => s.titulo === 'Anúncios')?.texto.includes('Não informado'));
const stale = montarRelatorioSemanal(clientes, [antigo], [], '2026-11-21', '2026-11-27', '2026-11-27');
assert.equal(stale.itens[0].atualizada, false, 'ficha anterior não passa por revisão desta semana');
assert.throws(() => montarRelatorioSemanal(clientes, [], [], '2026-11-28', '2026-11-21', '2026-11-27'));
console.log('Relatório semanal: cobertura, corte temporal, pendências e compatibilidade validados.');
